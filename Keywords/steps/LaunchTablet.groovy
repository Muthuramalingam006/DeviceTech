public class LaunchTablet {

	@Keyword
	def launchTabletView(String url) {
		// Open browser and set viewport to tablet dimensions
		WebUI.openBrowser('')
		WebUI.setViewPortSize(1024 , 1366) // Typical tablet size (iPad portrait)

		// Navigate to the target URL
		WebUI.navigateToUrl(url)

		// Optional: Log confirmation
		WebUI.comment("✅ Launched tablet view at 768x1024 for URL: " + url)
	}
}

